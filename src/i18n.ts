const getInitialLanguage = (): Language => {
  if (typeof window === 'undefined') return 'en';
  const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  if (saved === 'de' || saved === 'en') return saved;
  return window.navigator.language.toLowerCase().startsWith('de') ? 'de' : 'en';
};

let currentLanguage = getInitialLanguage();
const listeners = new Set<() => void>();

const updateDocumentLanguage = (language: Language) => {
  if (typeof document !== 'undefined') document.documentElement.lang = language === 'de' ? 'de' : 'en';
};

updateDocumentLanguage(currentLanguage);

export const getLanguage = (): Language => currentLanguage;

export const setLanguage = (language: Language) => {
  currentLanguage = language;
  if (typeof window !== 'undefined') window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  updateDocumentLanguage(language);
  listeners.forEach((listener) => listener());
};

export const translate = (key: string, params?: Record<string, string | number>): string => {
  const template = translations[currentLanguage][key] ?? translations.en[key] ?? key;
  return params
    ? template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(params[name] ?? `{{${name}}}`))
    : template;
};

export function useTranslation() {
  const [, rerender] = useState(0);

  useEffect(() => {
    const listener = () => rerender((value) => value + 1);
    listeners.add(listener);
    return () => {
      listeners.delete(listener);
    };
  }, []);

  return { t: translate, language: currentLanguage, setLanguage };
}
